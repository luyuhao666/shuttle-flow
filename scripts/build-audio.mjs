import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const root = new URL('../', import.meta.url);
function readWav(bytes) {
  assert.equal(bytes.toString('ascii', 0, 4), 'RIFF');
  assert.equal(bytes.toString('ascii', 8, 12), 'WAVE');
  let format, data;
  for (let offset = 12; offset + 8 <= bytes.length;) {
    const tag = bytes.toString('ascii', offset, offset + 4), size = bytes.readUInt32LE(offset + 4);
    if (tag === 'fmt ') format = { code: bytes.readUInt16LE(offset + 8), channels: bytes.readUInt16LE(offset + 10), rate: bytes.readUInt32LE(offset + 12), bits: bytes.readUInt16LE(offset + 22) };
    if (tag === 'data') data = bytes.subarray(offset + 8, offset + 8 + size);
    offset += 8 + size + size % 2;
  }
  assert.equal(format.code, 1); assert.ok([16, 24].includes(format.bits)); assert.ok(data);
  const width = format.bits / 8, samples = new Float64Array(data.length / (width * format.channels));
  for (let i = 0; i < samples.length; i++) for (let c = 0; c < format.channels; c++) samples[i] += data.readIntLE((i * format.channels + c) * width, width) / (2 ** (format.bits - 1) * format.channels);
  return { samples, rate: format.rate };
}
function clipWav(source, start, duration, highpass) {
  const { rate } = source, first = Math.floor(start * rate), samples = source.samples.slice(first, first + Math.floor(duration * rate));
  const alpha = 1 / (1 + 2 * Math.PI * highpass / rate); let previous = 0, output = 0;
  for (let i = 0; i < samples.length; i++) { const input = samples[i]; output = alpha * (output + input - previous); previous = input; samples[i] = output; }
  let peak = 0; for (const s of samples) peak = Math.max(peak, Math.abs(s)); assert.ok(peak > .02, 'Recording must contain an audible event');
  const pcm = Buffer.alloc(samples.length * 2);
  for (let i = 0; i < samples.length; i++) {
    const fade = Math.min(1, i / (rate * .001), (samples.length - 1 - i) / (rate * .02));
    pcm.writeInt16LE(Math.round(samples[i] / peak * .85 * fade * 32767), i * 2);
  }
  const header = Buffer.alloc(44); header.write('RIFF'); header.writeUInt32LE(36 + pcm.length, 4); header.write('WAVEfmt ', 8); header.writeUInt32LE(16, 16); header.writeUInt16LE(1, 20); header.writeUInt16LE(1, 22); header.writeUInt32LE(rate, 24); header.writeUInt32LE(rate * 2, 28); header.writeUInt16LE(2, 32); header.writeUInt16LE(16, 34); header.write('data', 36); header.writeUInt32LE(pcm.length, 40);
  return Buffer.concat([header, pcm]);
}
const sources = {};
for (const name of ['badminton', 'steps', 'swish']) sources[name] = readWav(await readFile(new URL(`assets/audio/${name}-original.wav`, root)));
const clips = [
  ['hit1', 'badminton', .112, .44, 70], ['hit2', 'badminton', 2.772, .44, 70],
  ['hit3', 'badminton', 5.690, .44, 70], ['hit4', 'badminton', 8.448, .44, 70],
  ['step1', 'steps', .027, .36, 100], ['step2', 'steps', .868, .36, 100],
  ['swish', 'swish', .275, .25, 150],
];
const encoded = {};
for (const [name, source, start, duration, highpass] of clips) {
  const wav = clipWav(sources[source], start, duration, highpass);
  await writeFile(new URL(`assets/audio/${name}.wav`, root), wav); encoded[name] = wav.toString('base64');
}
await writeFile(new URL('sounds.js', root), `// Generated by scripts/build-audio.mjs. Recording sources and CC0 licenses: assets/audio/CREDITS.md\n// Embedded WAV clips support file:// without fetch or a local server.\nglobalThis.ShuttleSounds = Object.freeze(${JSON.stringify(encoded)});\n`);
console.log(`Built ${clips.length} recorded audio clips and the offline sound bundle.`);
